    /// Build a fully-signed request for `path`. Pulled out of `get<T>`
    /// so the -403 WBI retry path can rebuild the request with fresh
    /// keys without duplicating header/cookie/cache-bust logic. Throws
    /// `invalidURL` if the URLComponents can't be assembled.
    ///
    /// `anonymousRequest` strips the iOS-client identity signals and
    /// forces an empty `Cookie` header — used by
    /// `AnonymousMainEndpoint` (and any future "B站 app-fingerprint"
    /// endpoint) to match the open-source B站 client
    /// `Starfallan/PiliNara`'s anonymous request shape. With
    /// BiliDroid User-Agent + `app-key` + `x-bili-aurora-zone` +
    /// `x-bili-trace-id` already set, sending the iOS-shape
    /// `mobi_app=iphone` / `platform=ios` / `Origin` headers at the
    /// same time is a fingerprint contradiction: the server reads it
    /// as a "third-party client pretending to be Android-HD" and
    /// returns -403 "访问权限不足" on the WBI comments endpoint.
    /// The empty `Cookie` is the matching PiliNara behavior — its
    /// anonymous options object sets `cookie: ''` explicitly so the
    /// server never sees a SESSDATA on the request (which would
    /// otherwise re-classify the call as a logged-in third-party
    /// client and gate it through a different code path).
    private func buildSignedRequest(
        baseURL: URL,
        path: String,
        queryItems: [URLQueryItem],
        signWithWBI: Bool,
        referer: String,
        anonymousRequest: Bool = false
    ) async throws -> URLRequest {
        var items = queryItems
        let isAppAPI = baseURL.host?.contains("app.bilibili.com") == true

        // Cache-bust web requests. App APIs have their own 'ts' parameter.
        if !isAppAPI {
            if !items.contains(where: { $0.name == "_t" }) {
                items.append(URLQueryItem(name: "_t", value: "\(Int(Date().timeIntervalSince1970 * 1000))"))
            }
            if !items.contains(where: { $0.name == "_r" }) {
                items.append(URLQueryItem(name: "_r", value: UUID().uuidString))
            }
        }

        if signWithWBI {
            items = try await wbiSigner.sign(queryItems: items, using: session)
        }

        var components = URLComponents(url: baseURL.appending(path: path), resolvingAgainstBaseURL: false)!
        components.queryItems = items
        guard let url = components.url else {
            throw BilibiliAPIError.invalidURL
        }

        var request = URLRequest(url: url)
        request.cachePolicy = .reloadIgnoringLocalCacheData
        // 10s request timeout. `URLSessionConfiguration` has
        // `waitsForConnectivity = true` (so the session will
        // hold a TCP connection open during transient network
        // drops) but no hard timeout — without this, the
        // comments endpoint has been observed to hang
        // indefinitely on the device with no response.
        // Surfacing a hard timeout lets the caller show the
        // error banner instead of an eternal spinner.
        request.timeoutInterval = 10
        request.setValue(referer, forHTTPHeaderField: "Referer")
        request.setValue(DeviceInfo.shared.userAgent, forHTTPHeaderField: "User-Agent")
        request.setValue("no-cache", forHTTPHeaderField: "Cache-Control")
        // Aurora / app-key / env / traceId headers — cross-referenced
        // from `Starfallan/PiliNara/lib/common/constants.dart`
        // `baseHeaders` and the `traceId` constant. PiliNara's
        // open-source B站 client reaches the comments endpoint
        // with this exact header set on every request and gets
        // the real reply list; without `traceId` the server
        // tracks the request as a non-official trace and gates
        // content (200 OK with `replies: null`).
        request.setValue("android64", forHTTPHeaderField: "app-key")
        request.setValue("sh001", forHTTPHeaderField: "x-bili-aurora-zone")
        request.setValue("prod", forHTTPHeaderField: "env")
        request.setValue("11111111111111111111111111111111:1111111111111111:0:0", forHTTPHeaderField: "x-bili-trace-id")
        // Match the canonical web client header set: B站
        // upstream appears to fingerprint non-iOS clients
        // missing `Accept` / `Accept-Language` / `Origin` and
        // hold the connection open (observed on
        // `/x/v2/reply/wbi/main` with `bili-universal/iphone`
        // UA but no Accept — web client with the same UA
        // string and full header set works fine). Setting them
        // here is cheap and removes a class of false-negative
        // silent hangs.
        request.setValue("application/json, text/plain, */*", forHTTPHeaderField: "Accept")
        request.setValue("zh-Hant-HK,zh-Hant;q=0.9,zh-CN;q=0.8,en-US;q=0.7,en;q=0.6", forHTTPHeaderField: "Accept-Language")
        // CRITICAL: send the iOS client identity headers on
        // EVERY B站 host, not just `app.bilibili.com`. The
        // official B站 iOS client attaches `mobi_app=iphone` and
        // `platform=ios` to every call (including the web API
        // at `api.bilibili.com`); B站's server uses the
        // presence of these headers as part of its content
        // gating logic. With the previous per-host `if/else`
        // branching, an `api.bilibili.com` request from Paladala
        // was mis-identified as a third-party web client even
        // though the User-Agent string said otherwise. The
        // server responded 200 OK with a valid `cursor` (so
        // `code: 0` passed `requireOK()` and the WBI retry
        // path did nothing) but the actual `replies[]` list
        // was empty — the canonical "missingIdentity" state
        // that we surfaced as `评论加载失败，请稍后重试`.
        //
        // Verified by manual test on the iPad: the official
        // B站 iOS app installed on the same device, viewing
        // the same video, sees the full comment list. The
        // diagnostic for the v0.5.7 build 307 attempt showed
        // `replies items=0 ... allCount=75` and a clean
        // `nextOffset` cursor — i.e. the server withheld
        // content but pretended the request succeeded.
        //
        // SKIPPED entirely when `anonymousRequest` is true —
        // see the long comment on `buildSignedRequest` above.
        // The new `AnonymousMainEndpoint` ships the
        // BiliDroid/2.0.1 User-Agent + `app-key`/`env`/
        // `x-bili-aurora-zone`/`x-bili-trace-id` headers, and
        // also sending `mobi_app=iphone`+`platform=ios` would
        // tell the server the client is simultaneously an
        // iOS-shape and Android-HD-shape client, which the
        // gating layer rejects with -403 on
        // `/x/v2/reply/wbi/main` and (presumably) the same on
        // `/x/v2/reply/main`. Drop the iOS headers for this
        // path.
        if !anonymousRequest {
            request.setValue("iphone", forHTTPHeaderField: "mobi_app")
            request.setValue("ios", forHTTPHeaderField: "platform")
        }
        if !anonymousRequest, !isAppAPI {
            // The web client also sends an `Origin` matching
            // the bilibili homepage — the official iOS app
            // omits it for the same hosts but its request is
            // already accepted without it. Adding it here
            // matches the canonical web client fingerprint
            // and keeps the "no missing identity" path open
            // for the few endpoints that do check it.
            request.setValue("https://www.bilibili.com", forHTTPHeaderField: "Origin")
        }

        if anonymousRequest {
            // Anonymous requests must NOT carry a SESSDATA.
            // PiliNara's anonymous options object (its
            // `lib/http/reply.dart` `Options(headers: {...,
            // 'cookie': ''})`) sets the `Cookie` header to an
            // explicit empty string rather than omitting the
            // header. URLSession treats `setValue("", ...)` as
            // "send the header with an empty value" which is
            // exactly what the server expects. We mirror that
            // so the request looks like a true
            // not-signed-in caller, even when the user has an
            // active SESSDATA in `HTTPCookieStorage` from a
            // previous session — the WebKit/iOS cookie store
            // would otherwise auto-attach the cookie and
            // re-classify the request as a logged-in
            // third-party client, which B站 gates
            // differently.
            request.setValue("", forHTTPHeaderField: "Cookie")
        } else if let cookie = await currentCookieHeader() {
            request.setValue(cookie, forHTTPHeaderField: "Cookie")
        }

        return request
    }

    /// Read the JSON `code` field out of a Bilibili envelope without
    /// needing `T` to be decodable. Used by `get<T>` to detect -403
    /// (the WBI drift signature) so it can refresh keys + retry once.
    /// Returns `nil` for non-Bilibili payloads (raw images, error
    /// pages, etc.) — caller treats that as "not a -403, do nothing".
    private static func envelopeCode(of data: Data) -> Int? {
        struct Envelope: Decodable { let code: Int? }
        return (try? JSONDecoder().decode(Envelope.self, from: data))?.code
            .flatMap { $0 }
    }

    // Internal visibility: the comment pipeline endpoints call
    // `get(...)` directly to issue their requests. The method is
    // unchanged — only the access modifier is widened so the
    // endpoints (which live in `CommentPipeline.swift`) can reach
    // it. The WBI sign retry path and the -403 / 风控 handling
    // already live inside `get<T>`; the endpoints inherit that
    // behavior for free.
    func get<T: Decodable>(
        baseURL: URL,
        path: String,
        queryItems: [URLQueryItem],
        signWithWBI: Bool = false,
        // Per-call Referer override. The default is the
        // bilibili-wide `https://www.bilibili.com`; some
        // endpoints (the suggest endpoint at
        // `s.search.bilibili.com`) expect the matching
        // referer (`https://search.bilibili.com`) so the
        // upstream doesn't reject the cross-host call.
        referer: String = "https://www.bilibili.com",
        // Diagnostic flags: when both are set, the first 4 KB
        // of the response body is dumped to the diagnostic log
        // so we can see exactly what the upstream returned.
        // Used to figure out what the playurl HLS slot is
        // actually called.
        dumpRawBody: Bool = false,
        dumpTag: String = "",
        // Anonymous request mode — see the long comment on
        // `buildSignedRequest`. Skips iOS-shape identity
        // headers (`mobi_app=iphone`, `platform=ios`, web
        // `Origin`) and forces an empty `Cookie` so the call
        // looks like a BiliDroid-shape not-signed-in client,
        // matching the open-source B站 client
        // `Starfallan/PiliNara` (which uses this shape to
        // reach the comments endpoint without an
        // `access_key`). Used by `AnonymousMainEndpoint` to
        // hit `/x/v2/reply/main` anonymously.
        anonymousRequest: Bool = false
    ) async throws -> T {
        var request = try await buildSignedRequest(
            baseURL: baseURL,
            path: path,
            queryItems: queryItems,
            signWithWBI: signWithWBI,
            referer: referer,
            anonymousRequest: anonymousRequest
        )

        // Request-side log so a hung request leaves a trace
        // in the diagnostic. The bpLog on the caller side
        // ("fetching") fires before this; if we never see
        // "sent" below, the URLSession is the one hanging.
        // Logs the URL only (no Cookie / SESSDATA) to avoid
        // shipping credentials into the diagnostic file.
        bpLog("GET sending | path=\(path) wbi=\(signWithWBI) timeout=\(request.timeoutInterval)s url=\(request.url?.absoluteString ?? "?")")

        // 412 (B站 风控) and 429 (rate limit) are transient
        // signals from the upstream — back off once and try
        // again.  A second failure propagates as `http` so
        // the caller still surfaces the failure to the user.
        // 401 is intentionally NOT retried here: a session
        // expiry needs a fresh login, not a duplicate request
        // that will also 401.
        //
        // WBI-signed requests get a second retry path: when
        // the envelope code is one of the codes the upstream
        // uses to reject a stale signature, we invalidate the
        // cached img/sub keys, rebuild the request with the
        // freshly-fetched ones, and send once.  Covers:
        //   -403 访问权限不足  — explicit WBI signature reject
        //   -352 风控          — sometimes raised when the
        //                         upstream sees a signature it
        //                         can't validate against a
        //                         freshly-rotated key pair
        //   -101 未登录        — when the upstream also strips
        //                         the user's SESSDATA from the
        //                         view because the request
        //                         looked unsigned; refresh +
        //                         retry resolves it without a
        //                         forced re-login
        // Without this, the first stale-cache request bubbles
        // up as `api("访问权限不足")` and the user sees the
        // generic "评论加载失败" banner — exactly the regression
        // Round 12's commit message flagged as
        // out-of-scope-for-that-round.
        let initial: (Data, URLResponse)
        do {
            initial = try await session.data(for: request)
        } catch {
            // Pair with the "sending" log above so a hung
            // request (no "sent", just this "failed" with a
            // timeout error) shows up in the diagnostic as a
            // URLSession-level timeout rather than looking
            // like a silent hang.
            bpLog("GET failed | path=\(path) error=\(error)")
            throw error
        }
        let resolved: (Data, URLResponse)
        let initialStatus = (initial.1 as? HTTPURLResponse)?.statusCode
        let initialCode: Int? = (initialStatus == 200)
            ? Self.envelopeCode(of: initial.0)
            : nil
        if let initialStatus, initialStatus == 412 || initialStatus == 429 {
            bpLog("GET \(request.url?.absoluteString ?? "?") returned HTTP \(initialStatus) — backoff 1.2s + retry once")
            try await Task.sleep(for: .milliseconds(1_200))
            resolved = try await session.data(for: request)
        } else if signWithWBI, let initialCode,
                  initialCode == -403 || initialCode == -352 || initialCode == -101 {
            bpLog("GET \(request.url?.absoluteString ?? "?") returned code \(initialCode) — refreshing WBI keys + retry once")
            await wbiSigner.invalidate()
            request = try await buildSignedRequest(
                baseURL: baseURL,
                path: path,
                queryItems: queryItems,
                signWithWBI: signWithWBI,
                referer: referer,
                anonymousRequest: anonymousRequest
            )
            resolved = try await session.data(for: request)
        } else {
            resolved = initial
        }
        let (data, response) = resolved
        // Diagnostic: pair the "sending" log above with a
        // "sent" log so a hung request (no "sent" log) is
        // distinguishable from a request that returned
        // 200 but with a non-JSON body (silent "sent"). The
        // status code is also captured here for cross-check
        // against the 412 / 429 / 401 / WBI retry branches
        // earlier in this function.
        let sentStatus = (response as? HTTPURLResponse)?.statusCode ?? -1
        bpLog("GET sent | path=\(path) status=\(sentStatus) bytes=\(data.count)")
        // Diagnostic: when a WBI-signed call returns a non-zero
        // envelope code that we *didn't* retry above, log it so
        // the diagnostic report can show what the upstream
        // actually returned.  Cheap (one JSON decode of an
        // envelope) and confined to the failure path — successful
        // responses stay quiet.
        if signWithWBI,
           let code = Self.envelopeCode(of: data),
           code != 0 {
            bpLog("GET \(request.url?.absoluteString ?? "?") returned envelope code \(code) — caller will see this as BilibiliAPIError")
        }
        guard let http = response as? HTTPURLResponse, (200..<300).contains(http.statusCode) else {
            let status = (response as? HTTPURLResponse)?.statusCode ?? -1
            bpLog("GET \(request.url?.absoluteString ?? "?") returned HTTP \(status)")
            // 401 = session expired.  Surface a typed error
            // (instead of the generic `http`) and let the app
            // open the login sheet.  The latch in
            // the auth-failure latch collapses a burst of
            // concurrent 401s into a single sheet-open so a
            // single expiry doesn't stack three sheets on top of
            // each other.
            if status == 401 {
                reportAuthFailureIfNeeded()
                throw BilibiliAPIError.sessionExpired
            }
            throw BilibiliAPIError.http
        }
        if dumpRawBody {
            // Dump the first 4 KB.  Large enough to capture the
            // top-level keys + the start of the DASH manifest +
            // the (usually short) `hls` slot if present.
            // Truncate the dump to keep the diagnostic export
            // readable.
            let sample = String(data: data.prefix(4096), encoding: .utf8)
                ?? "<binary>"
            diagLog(.playback,
                    "playurl raw response dump (\(dumpTag))",
                    details: [
                        "bytes": data.count,
                        "body_prefix_4k": sample
                    ])
        }
        do {
            return try decoder.decode(T.self, from: data)
        } catch {
            bpLog("decode failed for \(request.url?.absoluteString ?? "?"): \(error)\n  body: \(String(data: data.prefix(512), encoding: .utf8) ?? "<binary>")")
            throw error
        }
    }

    @discardableResult
    func post<T: Decodable>(
        baseURL: URL,
        path: String,
        queryItems: [URLQueryItem] = [],
        parameters: [String: String] = [:],
        referer: String = "https://www.bilibili.com"
    ) async throws -> T {
        var items = parameters

        // Snapshot auth once so the CSRF token and Cookie header always
        // belong to the same account even if the user switches accounts
        // while this request is being assembled.
        let cookies = await currentCookieHeader()
        if let cookies {
            let pairs = cookies.components(separatedBy: ";")
            for pair in pairs {
                let parts = pair.trimmingCharacters(in: .whitespaces).split(
                    separator: "=",
                    maxSplits: 1,
                    omittingEmptySubsequences: false
                )
                if parts.count == 2 && parts[0] == "bili_jct" {
                    items["csrf"] = String(parts[1])
                    break
                }
            }
        }

        let bodyString = items.keys.sorted().map { key in
            "\(key)=\(encodeURIComponent(items[key] ?? ""))"
        }.joined(separator: "&")

        var components = URLComponents(url: baseURL.appending(path: path), resolvingAgainstBaseURL: false)!
        if !queryItems.isEmpty {
            components.queryItems = queryItems
        }
        
        guard let url = components.url else {
            throw BilibiliAPIError.invalidURL
        }

        var request = URLRequest(url: url)
        request.httpMethod = "POST"
        request.httpBody = bodyString.data(using: .utf8)
        request.setValue("application/x-www-form-urlencoded", forHTTPHeaderField: "Content-Type")
        request.setValue(referer, forHTTPHeaderField: "Referer")
        request.setValue(DeviceInfo.shared.userAgent, forHTTPHeaderField: "User-Agent")

        if let cookies {
            request.setValue(cookies, forHTTPHeaderField: "Cookie")
        }

        // 412 / 429 transient retry mirrors `get(...)` — see
        // the rationale there.  POSTs to gated endpoints
        // (like, follow, comment) can 412 under wind control
        // when the user submits a burst of actions, and 1.2s
        // is usually enough to clear the limit.
        let initial = try await session.data(for: request)
        let resolved: (Data, URLResponse)
        if let initialStatus = (initial.1 as? HTTPURLResponse)?.statusCode,
           initialStatus == 412 || initialStatus == 429 {
            bpLog("POST \(url.absoluteString) returned HTTP \(initialStatus) — backoff 1.2s + retry once")
            try await Task.sleep(for: .milliseconds(1_200))
            resolved = try await session.data(for: request)
        } else {
            resolved = initial
        }
        let (data, response) = resolved
        guard let http = response as? HTTPURLResponse, (200..<300).contains(http.statusCode) else {
            let status = (response as? HTTPURLResponse)?.statusCode ?? -1
            bpLog("POST \(url.absoluteString) returned HTTP \(status)")
            // Same 401 → sessionExpired mapping as `get(...)` —
            // POSTs to gated endpoints (post comment, like,
            // watch-later) all return 401 once the session is
            // dead, and the app needs to be able to surface the
            // login sheet without parsing the status code.
            if status == 401 {
                reportAuthFailureIfNeeded()
                throw BilibiliAPIError.sessionExpired
            }
            throw BilibiliAPIError.http
        }

        do {
            return try decoder.decode(T.self, from: data)
        } catch {
            bpLog("decode failed for POST \(url.absoluteString): \(error)")
            throw error
        }
    }

    private func encodeURIComponent(_ string: String) -> String {
        var allowed = CharacterSet.urlQueryAllowed
        allowed.remove(charactersIn: ":#[]@!$&'()*+,;=")
        return string.addingPercentEncoding(withAllowedCharacters: allowed) ?? string
    }

    /// Drop the cached WBI keys. The WBI comment endpoint calls this
    /// when it detects the silent gate (200 OK + empty `replies[]`
    /// + non-zero `allCount`) so the next signed request re-fetches
    /// `/x/web-interface/nav` and rebuilds the signature with fresh
    /// keys. Forwarded to the private `WbiSigner` actor.
    ///
    /// Promoted from a private `WbiSigner.invalidate()` call site so
    /// the comment pipeline can trigger the recovery without
    /// reaching into the signer directly.
    func invalidateWBISigner() async {
        await wbiSigner.invalidate()
    }
}

