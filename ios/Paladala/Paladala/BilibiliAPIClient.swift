private actor WbiSigner {
    private struct CachedKeys {
        let imgKey: String
        let subKey: String
        let fetchedAt: Date
    }

    private let mixinKeyEncTab = [
        46, 47, 18, 2, 53, 8, 23, 32, 15, 50, 10, 31, 58, 3, 45, 35, 27, 43, 5, 49,
        33, 9, 42, 19, 29, 28, 14, 39, 12, 38, 41, 13, 37, 48, 7, 16, 24, 55, 40,
        61, 26, 17, 0, 1, 60, 51, 30, 4, 22, 25, 54, 21, 56, 59, 6, 63, 57, 62, 11,
        36, 20, 34, 44, 52
    ]
    private let keyTTL: TimeInterval = 30 * 60
    private let navURL = URL(string: "https://api.bilibili.com/x/web-interface/nav")!
    private var cachedKeys: CachedKeys?

    /// Pre-fetched keys shared across all signer instances.
    /// Populated by `WbiSigner.prewarm(using:)` from
    /// `PaladalaApp.init()` so the first signed request
    /// doesn't pay the `/x/web-interface/nav` round-trip.
    /// Bypassed once the per-instance TTL cache is warm —
    /// the instance cache is the source of truth for
    /// staleness; the static cache is only the boot
    /// speed-up.
    private static var prewarmedKeys: CachedKeys?

    /// Best-effort boot-time fetch.  No-ops if the keys are
    /// already populated or the network call fails — the
    /// regular `loadKeys()` path will pick up the slack.
    static func prewarm(using session: URLSession) async {
        guard prewarmedKeys == nil else { return }
        do {
            var request = URLRequest(url: URL(string: "https://api.bilibili.com/x/web-interface/nav")!)
            request.cachePolicy = .reloadIgnoringLocalCacheData
            request.setValue("https://www.bilibili.com", forHTTPHeaderField: "Referer")
            request.setValue(DeviceInfo.shared.userAgent, forHTTPHeaderField: "User-Agent")
            let (data, _) = try await session.data(for: request)
            let payload = try JSONDecoder().decode(WbiNavResponse.self, from: data)
            let imgURL = payload.data.wbiImg.imgURL
            let subURL = payload.data.wbiImg.subURL
            prewarmedKeys = CachedKeys(
                imgKey: imgURL.deletingPathExtension().lastPathComponent,
                subKey: subURL.deletingPathExtension().lastPathComponent,
                fetchedAt: Date()
            )
            bpLog("WbiSigner prewarm: keys cached")
        } catch {
            // Non-fatal. First signed request will retry.
            bpLog("WbiSigner prewarm failed: \(error.localizedDescription)")
        }
    }

    /// Drop the cached WBI keys. Used when the upstream tells us our
    /// signature is no longer accepted (B站 rotates the img/sub keys on
    /// a cadence that outpaces our per-instance cache). The next signed
    /// request will re-fetch from `/x/web-interface/nav` and the
    /// caller's retry will succeed.  Clears both the per-instance and
    /// the boot-time static prewarm so a long-lived app can recover
    /// without a relaunch.
    func invalidate() {
        cachedKeys = nil
        Self.prewarmedKeys = nil
        bpLog("WbiSigner invalidated — keys will be re-fetched on next sign")
    }

    func sign(queryItems: [URLQueryItem], using session: URLSession) async throws -> [URLQueryItem] {
        let keys = try await loadKeys(using: session)
        let mixinKey = buildMixinKey(imgKey: keys.imgKey, subKey: keys.subKey)
        let timestamp = String(Int(Date().timeIntervalSince1970))

        var params: [String: String] = [:]
        for item in queryItems {
            guard let value = item.value else { continue }
            params[item.name] = value.replacingOccurrences(of: #"[!'()*]"#, with: "", options: .regularExpression)
        }
        params["wts"] = timestamp

        let sorted = params.keys.sorted().map { key in
            "\(key)=\(encodeURIComponent(params[key] ?? ""))"
        }.joined(separator: "&")
        params["w_rid"] = md5(sorted + mixinKey)

        return params.keys.sorted().map { key in
            URLQueryItem(name: key, value: params[key])
        }
    }

    private func loadKeys(using session: URLSession) async throws -> CachedKeys {
        if let cachedKeys, Date().timeIntervalSince(cachedKeys.fetchedAt) < keyTTL {
            return cachedKeys
        }
        // Lift the boot pre-warm into the per-instance cache
        // before going to the network.  Static cache is only
        // consulted when the instance cache is empty or
        // expired — TTL still applies.
        if let prewarmed = Self.prewarmedKeys,
           Date().timeIntervalSince(prewarmed.fetchedAt) < keyTTL {
            cachedKeys = prewarmed
            return prewarmed
        }

        var request = URLRequest(url: navURL)
        request.cachePolicy = .reloadIgnoringLocalCacheData
        request.setValue("https://www.bilibili.com", forHTTPHeaderField: "Referer")
        request.setValue(DeviceInfo.shared.userAgent, forHTTPHeaderField: "User-Agent")
        let (data, _) = try await session.data(for: request)
        let payload = try JSONDecoder().decode(WbiNavResponse.self, from: data)
        let imgURL = payload.data.wbiImg.imgURL
        let subURL = payload.data.wbiImg.subURL
        let keys = CachedKeys(
            imgKey: imgURL.deletingPathExtension().lastPathComponent,
            subKey: subURL.deletingPathExtension().lastPathComponent,
            fetchedAt: Date()
        )
        cachedKeys = keys
        return keys
    }

    private func buildMixinKey(imgKey: String, subKey: String) -> String {
        let source = Array(imgKey + subKey)
        let mixed = mixinKeyEncTab.compactMap { index in
            index < source.count ? source[index] : nil
        }
        return String(mixed.prefix(32))
    }

    private func encodeURIComponent(_ value: String) -> String {
        let allowed = CharacterSet.alphanumerics.union(CharacterSet(charactersIn: "-_.~"))
        return value.unicodeScalars.map { scalar in
            if allowed.contains(scalar) {
                return String(scalar)
            }
            let bytes = String(scalar).utf8.map { String(format: "%%%02X", $0) }
            return bytes.joined()
        }.joined()
    }

    private func md5(_ value: String) -> String {
        Insecure.MD5.hash(data: Data(value.utf8)).map { String(format: "%02x", $0) }.joined()
    }
}

enum BilibiliAPIError: Error, Sendable {
    case invalidURL
    case http
    case api(String)
    case missingData
    /// The endpoint we wanted to call requires an `aid` (or `bvid`) on the
    /// input and we have neither. Surfacing this as a typed error lets the
    /// caller show a clear "评论不可用" message instead of a generic
    /// "Could not load public comments." after a doomed network call.
    case missingIdentity
    /// The playurl endpoint returned a payload but every supported
    /// `qn` quality was gated (region lock, VIP paywall, 4K-only
    /// source). Distinct from `missingData` so the UI can say "暂无可
    /// 播放清晰度" rather than a generic "缺少数据".
    case noPlayableFormat
    /// The server returned HTTP 401 — the cookie session has
    /// expired or been invalidated (B站 rotates `SESSDATA` every
    /// ~30 days, and `bili_jct` after each login).  Distinct
    /// from `http` so the client can auto-open the login sheet
    /// and re-try the request once the user re-authenticates.
    case sessionExpired
    /// The user requested a quality / audio track that requires
    /// a 大会员 subscription but the active account does not
    /// have one. Carries the gated quality (when known) so the
    /// UI can render the matching toolbar label.
    ///
    /// Surfaced when the upstream playurl returns:
    ///   • `-62002` ("大会员已到期" — VIP lapsed)
    ///   • `-62004` ("4K 需要大会员" — 4K-only paywall)
    ///   • `-62012` ("1080P+ 需要大会员" — 1080P+ paywall)
    ///
    /// Distinct from `vipExpired` so the UI can split the
    /// "go upgrade" prompt (signed-in but not VIP) from the
    /// "your membership lapsed" prompt (signed-in, was VIP, now
    /// overdue). The two paths lead to different recovery
    /// actions — the former opens the upgrade page, the latter
    /// reopens the login sheet with the renewal hint.
    case vipRequired(gated: BiliVideoQuality?)
    /// The user had a 大会员 subscription but it has lapsed
    /// (`-40103` "大会员已到期" from the upstream playurl, or
    /// the nav `/x/web-interface/nav` `data.vip.status == 0`
    /// with a non-zero `due_date` in the past). Carries the
    /// gated quality (when known) so the UI can name the
    /// specific row that needs renewal.
    case vipExpired(gated: BiliVideoQuality?)

    /// B站 returns business code `-404` with the message
    /// `啥都木有` when a region/part feed (e.g. 音乐) has no
    /// items visible to the current viewer — either because
    /// the cookie is missing, the region is gated, or the
    /// upstream genuinely has nothing to show.  The wire
    /// response is the same shape as any other code, so
    /// callers normally get a thrown `api("啥都木有")`.  The
    /// UI, however, should treat this as the empty-feed
    /// state ("暂无音乐") rather than a network error.
    ///
    /// Use the `isEmptyFeed` helper below to check; do NOT
    /// pattern-match the raw message string at the call site.
    var isEmptyFeed: Bool {
        if case .api(let message) = self {
            return message == "啥都木有"
        }
        return false
    }

    /// True when the error is a 大会员-expired typed error
    /// (carries the `vipExpired(gated:)` case). Lets the
    /// `setPreferredQn` / `setPreferredAudioQuality` paths
    /// branch into the "续费" copy without pattern-matching
    /// the associated value at every call site.
    var isVipExpiredError: Bool {
        if case .vipExpired = self { return true }
        return false
    }
}

extension BilibiliAPIError: LocalizedError {
    var errorDescription: String? {
        switch self {
        case .invalidURL:
            return L10n.errors.parse
        case .http:
            return L10n.errors.network
        case .api(let message):
            // Forward the upstream message verbatim.  Anonymous
            // calls surface the well-known B站 business codes
            // here — e.g. `-404 啥都木有` ("nothing here") or
            // `-101 请先登录` ("please sign in").  Returning the
            // raw message lets callers show the upstream reason
            // instead of the unhelpful Swift default
            // "(Paladala.BilibiliAPIError error 0.)".
            return message
        case .missingData:
            return L10n.errors.parse
        case .missingIdentity:
            return L10n.errors.unauthorized
        case .noPlayableFormat:
            return L10n.errors.empty
        case .sessionExpired:
            return L10n.errors.unauthorized
        case .vipRequired:
            // "该画质/音质需要大会员" — the toolbar surfaces the
            // full "go upgrade" hint via the upgrade sheet; this
            // short message is what the inline `errorMessage`
            // banner shows until the user dismisses it.
            return L10n.vip.requiredHint
        case .vipExpired:
            return L10n.vip.expiredHint
        }
    }
}

