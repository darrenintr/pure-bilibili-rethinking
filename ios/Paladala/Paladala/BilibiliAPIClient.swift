// MARK: - App API signing credentials
//
// The public Bilibili App endpoints (`/x/v2/feed/index`, etc.) require a
// signature of the form `md5(sortedQueryString + appSec)`. The `appKey` /
// `appSec` pair below is the well-known, public **`云视听小电视` (TV/OTT)**
// client credentials from pskdje/bilibili-API-collect
// `docs/misc/sign/APPKey.md` — the same values used by the public
// doc-repo examples for the `/x/passport-tv-login/qrcode/*` endpoints.
//
// We deliberately use the **TV appkey** (not the pink-app / iOS
// appkey) so the `access_token` minted by the QR login flow in
// `BilibiliAuthAPI.appQrcodeGenerate/Poll` is paired with the
// same `appkey` every app-signed request here sends. B站 ties
// `access_key` to the minting `appkey` — using a mismatched pair
// silently fails authentication on the comments endpoint
// (`/x/v2/reply`). The pink-app appkey (`1d8b6e7d45233436`)
// that previously lived here is also valid for the
// feed/comments surfaces, but its `access_token`s cannot be
// obtained from the TV QR flow (`passport.bilibili.com` rejects
// it with `code=-403 访问权限不足`, verified 2026-08-02), so we
// standardise on the TV pair end-to-end.
//
// `buvid` is normally a per-install device fingerprint; we
// derive a stable placeholder from a fixed namespace so
// anonymous requests still carry the field the upstream
// expects.
//
// Computed per-device `buvid3` is provided by the `AuthStore` via the
// `appConfigProvider` closure for authenticated requests; anonymous
// requests use the stable format generated by `generateMobileBuvid()`.
// Internal visibility: the comment pipeline (`CommentPipeline.swift`)
// reads these to build app-signed queries for the `/x/v2/reply`
// endpoint family. Keep these grouped at the top of the file so the
// pipeline-side read sites land in one place.
let appKey = "4409e2ce8ffd12b8"
private let appSec = "59b43e04ad6965f34319062b478f83dd"
// Official iOS client build number. App-signed feed endpoints return a
// fuller, better-ranked batch when this is present (verified: 10 vs 8
// items) — it is part of the mobile identity the risk-control layer
// checks. We keep the iOS build because the Paladala client *is* an
// iOS app on the wire; the TV appkey is only used for signature
// parity with the login flow, not because we're claiming to be the
// TV client. If B站's 风控 layer starts rejecting the
// (TV-appkey, iOS-build) pairing, the next step is to also flip
// `mobi_app` / `platform` here — see the call sites at the
// per-endpoint query items.
// Internal visibility: paired with `appKey` above — the comment
// pipeline (`CommentPipeline.swift`) reads these as file-level
// constants when building the app-signed `/x/v2/reply` query.
let appBuild = "84900100"

