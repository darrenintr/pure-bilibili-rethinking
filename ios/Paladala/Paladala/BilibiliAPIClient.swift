struct VideoDTO: Decodable, Sendable {
    let bvid: String
    let aid: Int
    let cid: Int
    let title: String
    let ownerName: String
    let coverURL: URL?
    let duration: Int
    let viewCount: Int
    let danmakuCount: Int
    let likeCount: Int
    let favoriteCount: Int?
    let coinCount: Int?
    let shareCount: Int?
    /// Reply / comment count from the upstream `stat` block.
    /// Bilibili feeds (`/x/web-interface/index/feed`, recommend
    /// cards) and search results all return `stat` as a nested
    /// object — `reply` is the comment-count key.  The previous
    /// decoder only read `view` / `danmaku` / `like`, so the
    /// home feed silently showed 0 comments for every video
    /// even though `/x/web-interface/view` had the real number
    /// ready to read.
    let replyCount: Int
    /// Publish timestamp from the upstream `pubdate` field
    /// (Unix seconds).  Optional because some feed shapes
    /// (history rows, dynamic-feed archive, search result
    /// previews) don't surface it; the home card hides the
    /// date row when this is `nil`.
    let publishDate: Date?
    let description: String
    /// Owner's Bilibili `mid`. Read from `owner.mid` (the same
    /// nested container that owns `ownerName`). Surfaced on the
    /// resulting `BiliVideo` so the AI 视频总结 endpoint can send
    /// the required `up_mid` query parameter.
    let ownerMid: Int64

    var model: BiliVideo {
        BiliVideo(
            bvid: bvid,
            aid: aid,
            cid: cid,
            title: title,
            ownerName: ownerName,
            coverURL: coverURL,
            duration: duration,
            viewCount: viewCount,
            danmakuCount: danmakuCount,
            likeCount: likeCount,
            replyCount: replyCount,
            favoriteCount: favoriteCount,
            coinCount: coinCount,
            shareCount: shareCount,
            publishDate: publishDate,
            description: description,
            ownerMid: ownerMid
        )
    }

    var validModel: BiliVideo? {
        guard !bvid.isEmpty || aid > 0 else { return nil }
        guard !title.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return nil }
        return model
    }

    init(from decoder: Decoder) throws {
        let container = try decoder.container(keyedBy: DynamicKey.self)
        bvid = container.decodeString(keys: ["bvid", "param"]) ?? ""
        aid = container.decodeInt(keys: ["aid", "id"]) ?? 0
        cid = container.decodeInt(keys: ["cid"]) ?? 0
        title = container.decodeString(keys: ["title"])?.strippingHTML ?? "Untitled"
        coverURL = container.decodeString(keys: ["pic", "cover"])?.httpsURL
        duration = container.decodeInt(keys: ["duration"]) ?? 0
        description = container.decodeString(keys: ["desc", "description"]) ?? ""

        let owner = try? container.nestedContainer(keyedBy: DynamicKey.self, forKey: DynamicKey("owner"))
        let args = try? container.nestedContainer(keyedBy: DynamicKey.self, forKey: DynamicKey("args"))
        // Bilibili returns `owner.mid` + `owner.name` on the home
        // recommend feed but **flat** `mid` + `author` on the
        // web-search endpoint (`/x/web-interface/wbi/search/type`)
        // and on some app-feed payloads. Try both shapes so
        // search-result rows surface the UP correctly — without
        // this the row showed "Unknown" and `ownerMid == 0`,
        // which hid the UP entry card on `VideoDetailView`.
        ownerName = owner?.decodeString(keys: ["name"])
            ?? args?.decodeString(keys: ["up_name"])
            ?? container.decodeString(keys: ["author", "name"])
            ?? "Unknown"
        ownerMid = owner?.decodeInt64(keys: ["mid"])
            ?? args?.decodeInt64(keys: ["up_mid"])
            ?? container.decodeInt64(keys: ["mid"])
            ?? 0

        let stat = try? container.nestedContainer(keyedBy: DynamicKey.self, forKey: DynamicKey("stat"))
        viewCount = stat?.decodeInt(keys: ["view", "view_count"]) ?? container.decodeInt(keys: ["play"]) ?? 0
        danmakuCount = stat?.decodeInt(keys: ["danmaku"]) ?? container.decodeInt(keys: ["danmaku"]) ?? 0
        likeCount = stat?.decodeInt(keys: ["like"]) ?? 0
        favoriteCount = stat?.decodeInt(keys: ["favorite", "collect"])
        coinCount = stat?.decodeInt(keys: ["coin"])
        shareCount = stat?.decodeInt(keys: ["share"])
        // `stat.reply` is the comment count.  Bilibili writes it
        // on every `/x/web-interface/view` and most feed shapes
        // but a few (search result previews) only surface
        // `video_review` — accept both keys so the home card
        // doesn't drop to 0 for those.
        replyCount = stat?.decodeInt(keys: ["reply", "video_review"])
            ?? container.decodeInt(keys: ["reply", "video_review"])
            ?? 0
        // `pubdate` is a Unix-seconds timestamp on the
        // canonical /x/web-interface/view response.  Search
        // results and history rows don't always include it;
        // leave `nil` so the card hides the date row rather
        // than rendering "1970-01-01" for the missing case.
        if let pubdate = container.decodeInt64(keys: ["pubdate", "publish_date"]) {
            publishDate = Date(timeIntervalSince1970: TimeInterval(pubdate))
        } else {
            publishDate = nil
        }
    }
}
