// Internal visibility: the comment DTOs in `CommentPipeline.swift`
// use `DynamicKey` to read fields whose names drift across the
// upstream API revisions. Keeping the helper private would force
// each commentary-shape decoder to ship its own copy.
struct DynamicKey: CodingKey {
    let stringValue: String
    let intValue: Int? = nil

    init(_ stringValue: String) {
        self.stringValue = stringValue
    }

    init?(stringValue: String) {
        self.stringValue = stringValue
    }

    init?(intValue: Int) {
        return nil
    }
}

extension KeyedDecodingContainer where K == DynamicKey {
    func decodeString(keys: [String]) -> String? {
        for key in keys {
            if let value = try? decode(String.self, forKey: DynamicKey(key)) {
                return value
            }
            if let value = try? decode(Int.self, forKey: DynamicKey(key)) {
                return "\(value)"
            }
        }
        return nil
    }

    /// Decode an array of strings under any of `keys`.  Returns
    /// `nil` when none of the keys are present, an empty array
    /// when the key is present but the array is empty, and the
    /// raw strings otherwise.  Each element is left as a `String`
    /// — call sites that need `URL`s further filter via
    /// `compactMap { URL(string: $0) }` so a single malformed
    /// entry cannot poison the whole failover list.
    ///
    /// Used by the DASH decoders to read
    /// `backup_url` / `backupUrl` (the per-track CDN failover
    /// list B站 publishes alongside `base_url`).
    func decodeStringArray(keys: [String]) -> [String]? {
        for key in keys {
            if let arr = try? decode([String].self, forKey: DynamicKey(key)) {
                return arr
            }
            // Some B站 endpoints write the array as a single
            // string (legacy single-backup case); normalise.
            if let single = try? decode(String.self, forKey: DynamicKey(key)) {
                return [single]
            }
        }
        return nil
    }

    func decodeInt(keys: [String]) -> Int? {
        for key in keys {
            if let value = try? decode(Int.self, forKey: DynamicKey(key)) {
                return value
            }
            if let string = try? decode(String.self, forKey: DynamicKey(key)), let value = Int(string) {
                return value
            }
        }
        return nil
    }

    /// `decodeDouble` mirrors `decodeInt` but for the cases
    /// where the upstream writes the value as a number
    /// (`1.5`) instead of a string (`"1.5"`).  Bilibili's
    /// playurl response uses both shapes for `duration`
    /// (stringified seconds under `timelength`, raw seconds
    /// under `duration`).
    func decodeDouble(keys: [String]) -> Double? {
        for key in keys {
            if let value = try? decode(Double.self, forKey: DynamicKey(key)) {
                return value
            }
            if let value = try? decode(Int.self, forKey: DynamicKey(key)) {
                return Double(value)
            }
            if let string = try? decode(String.self, forKey: DynamicKey(key)), let value = Double(string) {
                return value
            }
        }
        return nil
    }

    func decodeInt64(keys: [String]) -> Int64? {
        for key in keys {
            if let value = try? decode(Int64.self, forKey: DynamicKey(key)) {
                return value
            }
            if let value = try? decode(Int.self, forKey: DynamicKey(key)) {
                return Int64(value)
            }
            if let string = try? decode(String.self, forKey: DynamicKey(key)), let value = Int64(string) {
                return value
            }
        }
        return nil
    }

    func decodeBool(keys: [String]) -> Bool? {
        for key in keys {
            if let value = try? decode(Bool.self, forKey: DynamicKey(key)) {
                return value
            }
            if let value = try? decode(Int.self, forKey: DynamicKey(key)) {
                return value != 0
            }
            if let string = try? decode(String.self, forKey: DynamicKey(key)) {
                switch string.lowercased() {
                case "1", "true":
                    return true
                case "0", "false":
                    return false
                default:
                    break
                }
            }
        }
        return nil
    }
}

// Internal visibility: the comment `Content` decoder in
// `CommentPipeline.swift` calls `strippingHTML` to normalise the
// `<em>...</em>` / `<a>...</a>` markup B站 leaves in the reply
// `message` field. The extension is widened so the comment pipeline
// can reach it without duplicating the regex.
extension String {
    var strippingHTML: String {
        replacingOccurrences(of: "<[^>]+>", with: "", options: .regularExpression)
    }

    var httpsURL: URL? {
        let source = hasPrefix("//") ? "https:\(self)" : self
        guard var components = URLComponents(string: source) else { return nil }
        if components.scheme == "http" {
            components.scheme = "https"
        }
        return components.url
    }
}

