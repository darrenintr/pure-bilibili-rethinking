import CryptoKit
import Foundation

// MARK: - App API signing credentials
//
// The public Bilibili App endpoints (`/x/v2/feed/index`, etc.) require a
// signature of the form `md5(sortedQueryString + appSec)`. The `appKey` /
// `appSec` pair below is the well-known, public **`云视听小电视` (TV/OTT)**
// client credentials from pskdje/bilibili-API-collect
// `docs/misc/sign/APPKey.md` — the same values used by the public
// doc-repo examples for the `/x/passport-tv-login/qrcode/*` endpoints.
//
// We deliberately use the **TV appkey** (not the pink-app / iOS
// appkey) so the `access_token` minted by the QR login flow in
// `BilibiliAuthAPI.appQrcodeGenerate/Poll` is paired with the
// same `appkey` every app-signed request here sends. B站 ties
// `access_key` to the minting `appkey` — using a mismatched pair
// silently fails authentication on the comments endpoint
// (`/x/v2/reply`). The pink-app appkey (`1d8b6e7d45233436`)
// that previously lived here is also valid for the
// feed/comments surfaces, but its `access_token`s cannot be
// obtained from the TV QR flow (`passport.bilibili.com` rejects
// it with `code=-403 访问权限不足`, verified 2026-08-02), so we
// standardise on the TV pair end-to-end.
//
// `buvid` is normally a per-install device fingerprint; we
// derive a stable placeholder from a fixed namespace so
// anonymous requests still carry the field the upstream
// expects.
//
// Computed per-device `buvid3` is provided by the `AuthStore` via the
// `appConfigProvider` closure for authenticated requests; anonymous
// requests use the stable format generated by `generateMobileBuvid()`.
// Internal visibility: the comment pipeline (`CommentPipeline.swift`)
// reads these to build app-signed queries for the `/x/v2/reply`
// endpoint family. Keep these grouped at the top of the file so the
// pipeline-side read sites land in one place.
let appKey = "4409e2ce8ffd12b8"
private let appSec = "59b43e04ad6965f34319062b478f83dd"
// Official iOS client build number. App-signed feed endpoints return a
// fuller, better-ranked batch when this is present (verified: 10 vs 8
// items) — it is part of the mobile identity the risk-control layer
// checks. We keep the iOS build because the Paladala client *is* an
// iOS app on the wire; the TV appkey is only used for signature
// parity with the login flow, not because we're claiming to be the
// TV client. If B站's 风控 layer starts rejecting the
// (TV-appkey, iOS-build) pairing, the next step is to also flip
// `mobi_app` / `platform` here — see the call sites at the
// per-endpoint query items.
// Internal visibility: paired with `appKey` above — the comment
// pipeline (`CommentPipeline.swift`) reads these as file-level
// constants when building the app-signed `/x/v2/reply` query.
let appBuild = "84900100"

final class BilibiliAPIClient: @unchecked Sendable {
    // Internal visibility: the comment pipeline reads `baseURL` to
    // build its endpoint URLs. Keeping the field at file-private scope
    // would force every endpoint to take a duplicated URL constant.
    let baseURL = URL(string: "https://api.bilibili.com")!
    let appBaseURL = URL(string: "https://app.bilibili.com")!
    let liveBaseURL = URL(string: "https://api.live.bilibili.com")!
    let accountBaseURL = URL(string: "https://account.bilibili.com")!
    /// Suggest endpoint base. Lives on `s.search.bilibili.com`
    /// (separate from `api.bilibili.com`) and is anonymous —
    /// no WBI signing, no SESSDATA required. Used by the
    /// keystroke-rate search-as-you-type path; verified to
    /// return in ~100 ms median via `scripts/probe_search_endpoints.py`
    /// on 2026-07-06.
    let suggestBaseURL = URL(string: "https://s.search.bilibili.com")!
    let session: URLSession
    let decoder: JSONDecoder
    private let wbiSigner = WbiSigner()
    /// Auth providers read `AuthStore`, which is main-actor isolated.
    /// Requests themselves may run on any executor, so we keep the
    /// provider references behind a lock and invoke their closures on
    /// the main actor through the async snapshot helpers below.
    private struct RequestProviderState {
        var cookieProvider: (@MainActor @Sendable () -> String?)?
        var appConfigProvider: (@MainActor @Sendable () -> BiliAppConfig?)?
    }

    private let requestProviderLock = NSLock()
    private var requestProviderState = RequestProviderState()

    /// Returns the active account's `Cookie:` header, or `nil` when the
    /// user is signed out. Re-evaluated for each request so an account
    /// switch takes effect without recreating the API client.
    var cookieProvider: (@MainActor @Sendable () -> String?)? {
        get {
            requestProviderLock.withLock { requestProviderState.cookieProvider }
        }
        set {
            requestProviderLock.withLock { requestProviderState.cookieProvider = newValue }
        }
    }

    /// Per-request mobile identity used by the App recommendation API.
    /// Like `cookieProvider`, the closure is main-actor isolated because
    /// it reads the currently selected account.
    var appConfigProvider: (@MainActor @Sendable () -> BiliAppConfig?)? {
        get {
            requestProviderLock.withLock { requestProviderState.appConfigProvider }
        }
        set {
            requestProviderLock.withLock { requestProviderState.appConfigProvider = newValue }
        }
    }

    func currentCookieHeader() async -> String? {
        let provider = requestProviderLock.withLock {
            requestProviderState.cookieProvider
        }
        return await provider?()
    }

    // Internal visibility: the comment pipeline reads the active
    // account's mobile identity (buvid3, access_key) to build the
    // app-signed `/x/v2/reply` request shape. The closure is
    // main-actor isolated, so the helper still hops off the call
    // executor before reaching into `AuthStore` — only the API
    // surface is widened.
    func currentAppConfig() async -> BiliAppConfig? {
        let provider = requestProviderLock.withLock {
            requestProviderState.appConfigProvider
        }
        return await provider?()
    }

    func hasAuthenticatedSession() async -> Bool {
        await currentCookieHeader() != nil
    }

    /// Mutable state used by the session-expiry interceptor. API
    /// requests can finish concurrently, so both the callback and
    /// its one-shot latch must be protected even though the client
    /// itself is intentionally `@unchecked Sendable`.
    private struct AuthFailureState {
        var handler: (@MainActor @Sendable () -> Void)?
        var hasReported = false
    }

    private let authFailureLock = NSLock()
    private var authFailureState = AuthFailureState()

    /// Fired on the main actor the first time a request returns HTTP
    /// 401 in an expiry episode. Subsequent concurrent 401 responses
    /// are collapsed by `authFailureState.hasReported` so they cannot
    /// stack multiple login sheets.
    var onAuthFailure: (@MainActor @Sendable () -> Void)? {
        get {
            authFailureLock.withLock { authFailureState.handler }
        }
        set {
            authFailureLock.withLock { authFailureState.handler = newValue }
        }
    }

    /// Reset the 401 latch after a successful login. Call this from
    /// `AuthStore.completeLogin(...)` so the next session expiry can
    /// re-open the sheet.
    func resetAuthFailureLatch() {
        authFailureLock.withLock { authFailureState.hasReported = false }
    }

    /// Atomically claims the one-shot callback, then hops to the main
    /// actor before touching UI state. If no handler has been wired yet,
    /// leave the latch open so a later 401 can still surface the prompt.
    private func reportAuthFailureIfNeeded() {
        let handler: (@MainActor @Sendable () -> Void)? = authFailureLock.withLock {
            guard !authFailureState.hasReported,
                  let handler = authFailureState.handler else {
                return nil
            }
            authFailureState.hasReported = true
            return handler
        }
        guard let handler else { return }
        Task { @MainActor in
            handler()
        }
    }

    /// Static fallback when no account is signed in.  Kept on the
    /// client so unit tests and the cached-`BiliAppConfig` callers
    /// can read the same placeholder value the API originally used.
    static var defaultConfig: BiliAppConfig {
        BiliAppConfig(buvid3: nil, mid: 0, csrf: nil, accessKey: nil)
    }

    init(session: URLSession? = nil) {
        if let session {
            self.session = session
        } else {
            // The default `URLSession.shared` returns immediately with
            // `NSURLErrorNotConnectedToInternet` on a weak link and never
            // retries. For the Paladala public feeds that is the dominant
            // failure mode on first launch. A 15 s request / 60 s resource
            // timeout with `waitsForConnectivity = true` lets the request
            // ride out brief network drops without failing the whole feed.
            let config = URLSessionConfiguration.default
            config.timeoutIntervalForRequest = 15
            config.timeoutIntervalForResource = 60
            config.waitsForConnectivity = true
            config.requestCachePolicy = .reloadIgnoringLocalCacheData
            config.httpAdditionalHeaders = [
                "User-Agent": DeviceInfo.shared.userAgent,
                "Referer": "https://www.bilibili.com"
            ]
            self.session = URLSession(configuration: config)
        }
        self.decoder = JSONDecoder()
    }

    /// Boot-time pre-fetch of the WBI signing keys.  Builds
    /// its own short-lived URLSession with the same defaults
    /// as `init(session:)` (so headers, timeouts, and
    /// connectivity wait all match) and forwards to the
    /// private `WbiSigner.prewarm(using:)`.  Safe to call
    /// from `PaladalaApp.init()` without an existing
    /// client instance.
    static func prewarmWbiKeys() async {
        let config = URLSessionConfiguration.default
        config.timeoutIntervalForRequest = 15
        config.timeoutIntervalForResource = 60
        config.waitsForConnectivity = true
        config.requestCachePolicy = .reloadIgnoringLocalCacheData
        config.httpAdditionalHeaders = [
            "User-Agent": DeviceInfo.shared.userAgent,
            "Referer": "https://www.bilibili.com"
        ]
        let session = URLSession(configuration: config)
        await WbiSigner.prewarm(using: session)
    }

    // Internal visibility: the app-signed `CommentEndpoint` reads
    // this to build the `sign` query item for `/x/v2/reply`. The
    // algorithm itself is unchanged — see the original doc comment
    // below.
    func appSign(_ queryItems: [URLQueryItem]) -> String {
        let sorted = queryItems.sorted { $0.name < $1.name }
        let query = sorted.compactMap { item -> String? in
            guard let value = item.value else { return nil }
            return "\(item.name)=\(value)"
        }.joined(separator: "&")
        return md5(query + appSec)
    }

    // Internal visibility: the app-signed `CommentEndpoint` may
    // need a buvid3 stand-in when the active account has none
    // (anonymous reads on the `app.bilibili.com` flavour).
    func generateMobileBuvid() -> String {
        // Official algorithm: XY + MD5(hwID) + 3 specific chars from hash
        // For simplicity and stability, we use a fixed but valid format.
        // Keep the legacy seed stable across the Paladala rebrand so
        // existing installs retain the same anonymous device identity.
        let seed = "Paladala-iOS-Device-Seed"
        let hash = md5(seed).uppercased()
        let c1 = hash[hash.index(hash.startIndex, offsetBy: 2)]
        let c2 = hash[hash.index(hash.startIndex, offsetBy: 12)]
        let c3 = hash[hash.index(hash.startIndex, offsetBy: 22)]
        return "XY\(c1)\(c2)\(c3)\(hash)"
    }

    private func md5(_ string: String) -> String {
        Insecure.MD5.hash(data: Data(string.utf8)).map { String(format: "%02x", $0) }.joined()
    }

    /// Raw-body companion to `get<T>`.  Same retry / referer
    /// / WBI-sign behaviour as `get<T>`, but returns the
    /// raw `Data` so the PGC playurl path can re-decode the
    /// `result.video_info` JSON object as the UGC-shaped
    /// `PlayURLPayload` without forcing the DASH sub-DTOs
    /// to implement `Encodable`.  Bypasses the `Decodable`
    /// return contract.
    func rawGet(
        baseURL: URL,
        path: String,
        queryItems: [URLQueryItem],
        signWithWBI: Bool = false
    ) async throws -> Data {
        var request = try await buildSignedRequest(
            baseURL: baseURL,
            path: path,
            queryItems: queryItems,
            signWithWBI: signWithWBI,
            referer: "https://www.bilibili.com"
        )
        let initial = try await session.data(for: request)
        let resolved: (Data, URLResponse)
        let initialStatus = (initial.1 as? HTTPURLResponse)?.statusCode
        let initialCode: Int? = initialStatus == 200 ? Self.envelopeCode(of: initial.0) : nil
        if let initialStatus, initialStatus == 412 || initialStatus == 429 {
            try await Task.sleep(for: .milliseconds(1_200))
            resolved = try await session.data(for: request)
        } else if signWithWBI, let initialCode,
                  initialCode == -403 || initialCode == -352 || initialCode == -101 {
            await wbiSigner.invalidate()
            request = try await buildSignedRequest(
                baseURL: baseURL,
                path: path,
                queryItems: queryItems,
                signWithWBI: true,
                referer: "https://www.bilibili.com"
            )
            resolved = try await session.data(for: request)
        } else {
            resolved = initial
        }
        let (data, response) = resolved
        guard let http = response as? HTTPURLResponse,
              (200..<300).contains(http.statusCode) else {
            throw BilibiliAPIError.http
        }
        if let code = Self.envelopeCode(of: data), code != 0,
           let envelope = try? JSONDecoder().decode(APIResponse<EmptyPayload>.self, from: data) {
            try envelope.requireOK()
        }
        return data
    }

    /// Build a fully-signed request for `path`. Pulled out of `get<T>`
    /// so the -403 WBI retry path can rebuild the request with fresh
    /// keys without duplicating header/cookie/cache-bust logic. Throws
    /// `invalidURL` if the URLComponents can't be assembled.
    ///
    /// `anonymousRequest` strips the iOS-client identity signals and
    /// forces an empty `Cookie` header — used by
    /// `AnonymousMainEndpoint` (and any future "B站 app-fingerprint"
    /// endpoint) to match the open-source B站 client
    /// `Starfallan/PiliNara`'s anonymous request shape. With
    /// BiliDroid User-Agent + `app-key` + `x-bili-aurora-zone` +
    /// `x-bili-trace-id` already set, sending the iOS-shape
    /// `mobi_app=iphone` / `platform=ios` / `Origin` headers at the
    /// same time is a fingerprint contradiction: the server reads it
    /// as a "third-party client pretending to be Android-HD" and
    /// returns -403 "访问权限不足" on the WBI comments endpoint.
    /// The empty `Cookie` is the matching PiliNara behavior — its
    /// anonymous options object sets `cookie: ''` explicitly so the
    /// server never sees a SESSDATA on the request (which would
    /// otherwise re-classify the call as a logged-in third-party
    /// client and gate it through a different code path).
    private func buildSignedRequest(
        baseURL: URL,
        path: String,
        queryItems: [URLQueryItem],
        signWithWBI: Bool,
        referer: String,
        anonymousRequest: Bool = false
    ) async throws -> URLRequest {
        var items = queryItems
        let isAppAPI = baseURL.host?.contains("app.bilibili.com") == true

        // Cache-bust web requests. App APIs have their own 'ts' parameter.
        if !isAppAPI {
            if !items.contains(where: { $0.name == "_t" }) {
                items.append(URLQueryItem(name: "_t", value: "\(Int(Date().timeIntervalSince1970 * 1000))"))
            }
            if !items.contains(where: { $0.name == "_r" }) {
                items.append(URLQueryItem(name: "_r", value: UUID().uuidString))
            }
        }

        if signWithWBI {
            items = try await wbiSigner.sign(queryItems: items, using: session)
        }

        var components = URLComponents(url: baseURL.appending(path: path), resolvingAgainstBaseURL: false)!
        components.queryItems = items
        guard let url = components.url else {
            throw BilibiliAPIError.invalidURL
        }

        var request = URLRequest(url: url)
        request.cachePolicy = .reloadIgnoringLocalCacheData
        // 10s request timeout. `URLSessionConfiguration` has
        // `waitsForConnectivity = true` (so the session will
        // hold a TCP connection open during transient network
        // drops) but no hard timeout — without this, the
        // comments endpoint has been observed to hang
        // indefinitely on the device with no response.
        // Surfacing a hard timeout lets the caller show the
        // error banner instead of an eternal spinner.
        request.timeoutInterval = 10
        request.setValue(referer, forHTTPHeaderField: "Referer")
        request.setValue(DeviceInfo.shared.userAgent, forHTTPHeaderField: "User-Agent")
        request.setValue("no-cache", forHTTPHeaderField: "Cache-Control")
        // Aurora / app-key / env / traceId headers — cross-referenced
        // from `Starfallan/PiliNara/lib/common/constants.dart`
        // `baseHeaders` and the `traceId` constant. PiliNara's
        // open-source B站 client reaches the comments endpoint
        // with this exact header set on every request and gets
        // the real reply list; without `traceId` the server
        // tracks the request as a non-official trace and gates
        // content (200 OK with `replies: null`).
        request.setValue("android64", forHTTPHeaderField: "app-key")
        request.setValue("sh001", forHTTPHeaderField: "x-bili-aurora-zone")
        request.setValue("prod", forHTTPHeaderField: "env")
        request.setValue("11111111111111111111111111111111:1111111111111111:0:0", forHTTPHeaderField: "x-bili-trace-id")
        // Match the canonical web client header set: B站
        // upstream appears to fingerprint non-iOS clients
        // missing `Accept` / `Accept-Language` / `Origin` and
        // hold the connection open (observed on
        // `/x/v2/reply/wbi/main` with `bili-universal/iphone`
        // UA but no Accept — web client with the same UA
        // string and full header set works fine). Setting them
        // here is cheap and removes a class of false-negative
        // silent hangs.
        request.setValue("application/json, text/plain, */*", forHTTPHeaderField: "Accept")
        request.setValue("zh-Hant-HK,zh-Hant;q=0.9,zh-CN;q=0.8,en-US;q=0.7,en;q=0.6", forHTTPHeaderField: "Accept-Language")
        // CRITICAL: send the iOS client identity headers on
        // EVERY B站 host, not just `app.bilibili.com`. The
        // official B站 iOS client attaches `mobi_app=iphone` and
        // `platform=ios` to every call (including the web API
        // at `api.bilibili.com`); B站's server uses the
        // presence of these headers as part of its content
        // gating logic. With the previous per-host `if/else`
        // branching, an `api.bilibili.com` request from Paladala
        // was mis-identified as a third-party web client even
        // though the User-Agent string said otherwise. The
        // server responded 200 OK with a valid `cursor` (so
        // `code: 0` passed `requireOK()` and the WBI retry
        // path did nothing) but the actual `replies[]` list
        // was empty — the canonical "missingIdentity" state
        // that we surfaced as `评论加载失败，请稍后重试`.
        //
        // Verified by manual test on the iPad: the official
        // B站 iOS app installed on the same device, viewing
        // the same video, sees the full comment list. The
        // diagnostic for the v0.5.7 build 307 attempt showed
        // `replies items=0 ... allCount=75` and a clean
        // `nextOffset` cursor — i.e. the server withheld
        // content but pretended the request succeeded.
        //
        // SKIPPED entirely when `anonymousRequest` is true —
        // see the long comment on `buildSignedRequest` above.
        // The new `AnonymousMainEndpoint` ships the
        // BiliDroid/2.0.1 User-Agent + `app-key`/`env`/
        // `x-bili-aurora-zone`/`x-bili-trace-id` headers, and
        // also sending `mobi_app=iphone`+`platform=ios` would
        // tell the server the client is simultaneously an
        // iOS-shape and Android-HD-shape client, which the
        // gating layer rejects with -403 on
        // `/x/v2/reply/wbi/main` and (presumably) the same on
        // `/x/v2/reply/main`. Drop the iOS headers for this
        // path.
        if !anonymousRequest {
            request.setValue("iphone", forHTTPHeaderField: "mobi_app")
            request.setValue("ios", forHTTPHeaderField: "platform")
        }
        if !anonymousRequest, !isAppAPI {
            // The web client also sends an `Origin` matching
            // the bilibili homepage — the official iOS app
            // omits it for the same hosts but its request is
            // already accepted without it. Adding it here
            // matches the canonical web client fingerprint
            // and keeps the "no missing identity" path open
            // for the few endpoints that do check it.
            request.setValue("https://www.bilibili.com", forHTTPHeaderField: "Origin")
        }

        if anonymousRequest {
            // Anonymous requests must NOT carry a SESSDATA.
            // PiliNara's anonymous options object (its
            // `lib/http/reply.dart` `Options(headers: {...,
            // 'cookie': ''})`) sets the `Cookie` header to an
            // explicit empty string rather than omitting the
            // header. URLSession treats `setValue("", ...)` as
            // "send the header with an empty value" which is
            // exactly what the server expects. We mirror that
            // so the request looks like a true
            // not-signed-in caller, even when the user has an
            // active SESSDATA in `HTTPCookieStorage` from a
            // previous session — the WebKit/iOS cookie store
            // would otherwise auto-attach the cookie and
            // re-classify the request as a logged-in
            // third-party client, which B站 gates
            // differently.
            request.setValue("", forHTTPHeaderField: "Cookie")
        } else if let cookie = await currentCookieHeader() {
            request.setValue(cookie, forHTTPHeaderField: "Cookie")
        }

        return request
    }

    /// Read the JSON `code` field out of a Bilibili envelope without
    /// needing `T` to be decodable. Used by `get<T>` to detect -403
    /// (the WBI drift signature) so it can refresh keys + retry once.
    /// Returns `nil` for non-Bilibili payloads (raw images, error
    /// pages, etc.) — caller treats that as "not a -403, do nothing".
    private static func envelopeCode(of data: Data) -> Int? {
        struct Envelope: Decodable { let code: Int? }
        return (try? JSONDecoder().decode(Envelope.self, from: data))?.code
            .flatMap { $0 }
    }

    // Internal visibility: the comment pipeline endpoints call
    // `get(...)` directly to issue their requests. The method is
    // unchanged — only the access modifier is widened so the
    // endpoints (which live in `CommentPipeline.swift`) can reach
    // it. The WBI sign retry path and the -403 / 风控 handling
    // already live inside `get<T>`; the endpoints inherit that
    // behavior for free.
    func get<T: Decodable>(
        baseURL: URL,
        path: String,
        queryItems: [URLQueryItem],
        signWithWBI: Bool = false,
        // Per-call Referer override. The default is the
        // bilibili-wide `https://www.bilibili.com`; some
        // endpoints (the suggest endpoint at
        // `s.search.bilibili.com`) expect the matching
        // referer (`https://search.bilibili.com`) so the
        // upstream doesn't reject the cross-host call.
        referer: String = "https://www.bilibili.com",
        // Diagnostic flags: when both are set, the first 4 KB
        // of the response body is dumped to the diagnostic log
        // so we can see exactly what the upstream returned.
        // Used to figure out what the playurl HLS slot is
        // actually called.
        dumpRawBody: Bool = false,
        dumpTag: String = "",
        // Anonymous request mode — see the long comment on
        // `buildSignedRequest`. Skips iOS-shape identity
        // headers (`mobi_app=iphone`, `platform=ios`, web
        // `Origin`) and forces an empty `Cookie` so the call
        // looks like a BiliDroid-shape not-signed-in client,
        // matching the open-source B站 client
        // `Starfallan/PiliNara` (which uses this shape to
        // reach the comments endpoint without an
        // `access_key`). Used by `AnonymousMainEndpoint` to
        // hit `/x/v2/reply/main` anonymously.
        anonymousRequest: Bool = false
    ) async throws -> T {
        var request = try await buildSignedRequest(
            baseURL: baseURL,
            path: path,
            queryItems: queryItems,
            signWithWBI: signWithWBI,
            referer: referer,
            anonymousRequest: anonymousRequest
        )

        // Request-side log so a hung request leaves a trace
        // in the diagnostic. The bpLog on the caller side
        // ("fetching") fires before this; if we never see
        // "sent" below, the URLSession is the one hanging.
        // Logs the URL only (no Cookie / SESSDATA) to avoid
        // shipping credentials into the diagnostic file.
        bpLog("GET sending | path=\(path) wbi=\(signWithWBI) timeout=\(request.timeoutInterval)s url=\(request.url?.absoluteString ?? "?")")

        // 412 (B站 风控) and 429 (rate limit) are transient
        // signals from the upstream — back off once and try
        // again.  A second failure propagates as `http` so
        // the caller still surfaces the failure to the user.
        // 401 is intentionally NOT retried here: a session
        // expiry needs a fresh login, not a duplicate request
        // that will also 401.
        //
        // WBI-signed requests get a second retry path: when
        // the envelope code is one of the codes the upstream
        // uses to reject a stale signature, we invalidate the
        // cached img/sub keys, rebuild the request with the
        // freshly-fetched ones, and send once.  Covers:
        //   -403 访问权限不足  — explicit WBI signature reject
        //   -352 风控          — sometimes raised when the
        //                         upstream sees a signature it
        //                         can't validate against a
        //                         freshly-rotated key pair
        //   -101 未登录        — when the upstream also strips
        //                         the user's SESSDATA from the
        //                         view because the request
        //                         looked unsigned; refresh +
        //                         retry resolves it without a
        //                         forced re-login
        // Without this, the first stale-cache request bubbles
        // up as `api("访问权限不足")` and the user sees the
        // generic "评论加载失败" banner — exactly the regression
        // Round 12's commit message flagged as
        // out-of-scope-for-that-round.
        let initial: (Data, URLResponse)
        do {
            initial = try await session.data(for: request)
        } catch {
            // Pair with the "sending" log above so a hung
            // request (no "sent", just this "failed" with a
            // timeout error) shows up in the diagnostic as a
            // URLSession-level timeout rather than looking
            // like a silent hang.
            bpLog("GET failed | path=\(path) error=\(error)")
            throw error
        }
        let resolved: (Data, URLResponse)
        let initialStatus = (initial.1 as? HTTPURLResponse)?.statusCode
        let initialCode: Int? = (initialStatus == 200)
            ? Self.envelopeCode(of: initial.0)
            : nil
        if let initialStatus, initialStatus == 412 || initialStatus == 429 {
            bpLog("GET \(request.url?.absoluteString ?? "?") returned HTTP \(initialStatus) — backoff 1.2s + retry once")
            try await Task.sleep(for: .milliseconds(1_200))
            resolved = try await session.data(for: request)
        } else if signWithWBI, let initialCode,
                  initialCode == -403 || initialCode == -352 || initialCode == -101 {
            bpLog("GET \(request.url?.absoluteString ?? "?") returned code \(initialCode) — refreshing WBI keys + retry once")
            await wbiSigner.invalidate()
            request = try await buildSignedRequest(
                baseURL: baseURL,
                path: path,
                queryItems: queryItems,
                signWithWBI: signWithWBI,
                referer: referer,
                anonymousRequest: anonymousRequest
            )
            resolved = try await session.data(for: request)
        } else {
            resolved = initial
        }
        let (data, response) = resolved
        // Diagnostic: pair the "sending" log above with a
        // "sent" log so a hung request (no "sent" log) is
        // distinguishable from a request that returned
        // 200 but with a non-JSON body (silent "sent"). The
        // status code is also captured here for cross-check
        // against the 412 / 429 / 401 / WBI retry branches
        // earlier in this function.
        let sentStatus = (response as? HTTPURLResponse)?.statusCode ?? -1
        bpLog("GET sent | path=\(path) status=\(sentStatus) bytes=\(data.count)")
        // Diagnostic: when a WBI-signed call returns a non-zero
        // envelope code that we *didn't* retry above, log it so
        // the diagnostic report can show what the upstream
        // actually returned.  Cheap (one JSON decode of an
        // envelope) and confined to the failure path — successful
        // responses stay quiet.
        if signWithWBI,
           let code = Self.envelopeCode(of: data),
           code != 0 {
            bpLog("GET \(request.url?.absoluteString ?? "?") returned envelope code \(code) — caller will see this as BilibiliAPIError")
        }
        guard let http = response as? HTTPURLResponse, (200..<300).contains(http.statusCode) else {
            let status = (response as? HTTPURLResponse)?.statusCode ?? -1
            bpLog("GET \(request.url?.absoluteString ?? "?") returned HTTP \(status)")
            // 401 = session expired.  Surface a typed error
            // (instead of the generic `http`) and let the app
            // open the login sheet.  The latch in
            // the auth-failure latch collapses a burst of
            // concurrent 401s into a single sheet-open so a
            // single expiry doesn't stack three sheets on top of
            // each other.
            if status == 401 {
                reportAuthFailureIfNeeded()
                throw BilibiliAPIError.sessionExpired
            }
            throw BilibiliAPIError.http
        }
        if dumpRawBody {
            // Dump the first 4 KB.  Large enough to capture the
            // top-level keys + the start of the DASH manifest +
            // the (usually short) `hls` slot if present.
            // Truncate the dump to keep the diagnostic export
            // readable.
            let sample = String(data: data.prefix(4096), encoding: .utf8)
                ?? "<binary>"
            diagLog(.playback,
                    "playurl raw response dump (\(dumpTag))",
                    details: [
                        "bytes": data.count,
                        "body_prefix_4k": sample
                    ])
        }
        do {
            return try decoder.decode(T.self, from: data)
        } catch {
            bpLog("decode failed for \(request.url?.absoluteString ?? "?"): \(error)\n  body: \(String(data: data.prefix(512), encoding: .utf8) ?? "<binary>")")
            throw error
        }
    }

    @discardableResult
    func post<T: Decodable>(
        baseURL: URL,
        path: String,
        queryItems: [URLQueryItem] = [],
        parameters: [String: String] = [:],
        referer: String = "https://www.bilibili.com"
    ) async throws -> T {
        var items = parameters

        // Snapshot auth once so the CSRF token and Cookie header always
        // belong to the same account even if the user switches accounts
        // while this request is being assembled.
        let cookies = await currentCookieHeader()
        if let cookies {
            let pairs = cookies.components(separatedBy: ";")
            for pair in pairs {
                let parts = pair.trimmingCharacters(in: .whitespaces).split(
                    separator: "=",
                    maxSplits: 1,
                    omittingEmptySubsequences: false
                )
                if parts.count == 2 && parts[0] == "bili_jct" {
                    items["csrf"] = String(parts[1])
                    break
                }
            }
        }

        let bodyString = items.keys.sorted().map { key in
            "\(key)=\(encodeURIComponent(items[key] ?? ""))"
        }.joined(separator: "&")

        var components = URLComponents(url: baseURL.appending(path: path), resolvingAgainstBaseURL: false)!
        if !queryItems.isEmpty {
            components.queryItems = queryItems
        }
        
        guard let url = components.url else {
            throw BilibiliAPIError.invalidURL
        }

        var request = URLRequest(url: url)
        request.httpMethod = "POST"
        request.httpBody = bodyString.data(using: .utf8)
        request.setValue("application/x-www-form-urlencoded", forHTTPHeaderField: "Content-Type")
        request.setValue(referer, forHTTPHeaderField: "Referer")
        request.setValue(DeviceInfo.shared.userAgent, forHTTPHeaderField: "User-Agent")

        if let cookies {
            request.setValue(cookies, forHTTPHeaderField: "Cookie")
        }

        // 412 / 429 transient retry mirrors `get(...)` — see
        // the rationale there.  POSTs to gated endpoints
        // (like, follow, comment) can 412 under wind control
        // when the user submits a burst of actions, and 1.2s
        // is usually enough to clear the limit.
        let initial = try await session.data(for: request)
        let resolved: (Data, URLResponse)
        if let initialStatus = (initial.1 as? HTTPURLResponse)?.statusCode,
           initialStatus == 412 || initialStatus == 429 {
            bpLog("POST \(url.absoluteString) returned HTTP \(initialStatus) — backoff 1.2s + retry once")
            try await Task.sleep(for: .milliseconds(1_200))
            resolved = try await session.data(for: request)
        } else {
            resolved = initial
        }
        let (data, response) = resolved
        guard let http = response as? HTTPURLResponse, (200..<300).contains(http.statusCode) else {
            let status = (response as? HTTPURLResponse)?.statusCode ?? -1
            bpLog("POST \(url.absoluteString) returned HTTP \(status)")
            // Same 401 → sessionExpired mapping as `get(...)` —
            // POSTs to gated endpoints (post comment, like,
            // watch-later) all return 401 once the session is
            // dead, and the app needs to be able to surface the
            // login sheet without parsing the status code.
            if status == 401 {
                reportAuthFailureIfNeeded()
                throw BilibiliAPIError.sessionExpired
            }
            throw BilibiliAPIError.http
        }

        do {
            return try decoder.decode(T.self, from: data)
        } catch {
            bpLog("decode failed for POST \(url.absoluteString): \(error)")
            throw error
        }
    }

    private func encodeURIComponent(_ string: String) -> String {
        var allowed = CharacterSet.urlQueryAllowed
        allowed.remove(charactersIn: ":#[]@!$&'()*+,;=")
        return string.addingPercentEncoding(withAllowedCharacters: allowed) ?? string
    }

    /// Drop the cached WBI keys. The WBI comment endpoint calls this
    /// when it detects the silent gate (200 OK + empty `replies[]`
    /// + non-zero `allCount`) so the next signed request re-fetches
    /// `/x/web-interface/nav` and rebuilds the signature with fresh
    /// keys. Forwarded to the private `WbiSigner` actor.
    ///
    /// Promoted from a private `WbiSigner.invalidate()` call site so
    /// the comment pipeline can trigger the recovery without
    /// reaching into the signer directly.
    func invalidateWBISigner() async {
        await wbiSigner.invalidate()
    }
}

fileprivate extension String {
    /// Returns `nil` when the receiver is empty (or whitespace-only).
    /// Used when an optional API parameter should be omitted entirely
    /// rather than sent as an empty string — Bilibili treats empty
    /// `mid` / `buvid3` values as "anonymous fallback" rather than
    /// "drop this parameter", which is why we treat `""` as `nil` at
    /// the call site.
    var nilIfEmpty: String? {
        isEmpty ? nil : self
    }
}

private actor WbiSigner {
    private struct CachedKeys {
        let imgKey: String
        let subKey: String
        let fetchedAt: Date
    }

    private let mixinKeyEncTab = [
        46, 47, 18, 2, 53, 8, 23, 32, 15, 50, 10, 31, 58, 3, 45, 35, 27, 43, 5, 49,
        33, 9, 42, 19, 29, 28, 14, 39, 12, 38, 41, 13, 37, 48, 7, 16, 24, 55, 40,
        61, 26, 17, 0, 1, 60, 51, 30, 4, 22, 25, 54, 21, 56, 59, 6, 63, 57, 62, 11,
        36, 20, 34, 44, 52
    ]
    private let keyTTL: TimeInterval = 30 * 60
    private let navURL = URL(string: "https://api.bilibili.com/x/web-interface/nav")!
    private var cachedKeys: CachedKeys?

    /// Pre-fetched keys shared across all signer instances.
    /// Populated by `WbiSigner.prewarm(using:)` from
    /// `PaladalaApp.init()` so the first signed request
    /// doesn't pay the `/x/web-interface/nav` round-trip.
    /// Bypassed once the per-instance TTL cache is warm —
    /// the instance cache is the source of truth for
    /// staleness; the static cache is only the boot
    /// speed-up.
    private static var prewarmedKeys: CachedKeys?

    /// Best-effort boot-time fetch.  No-ops if the keys are
    /// already populated or the network call fails — the
    /// regular `loadKeys()` path will pick up the slack.
    static func prewarm(using session: URLSession) async {
        guard prewarmedKeys == nil else { return }
        do {
            var request = URLRequest(url: URL(string: "https://api.bilibili.com/x/web-interface/nav")!)
            request.cachePolicy = .reloadIgnoringLocalCacheData
            request.setValue("https://www.bilibili.com", forHTTPHeaderField: "Referer")
            request.setValue(DeviceInfo.shared.userAgent, forHTTPHeaderField: "User-Agent")
            let (data, _) = try await session.data(for: request)
            let payload = try JSONDecoder().decode(WbiNavResponse.self, from: data)
            let imgURL = payload.data.wbiImg.imgURL
            let subURL = payload.data.wbiImg.subURL
            prewarmedKeys = CachedKeys(
                imgKey: imgURL.deletingPathExtension().lastPathComponent,
                subKey: subURL.deletingPathExtension().lastPathComponent,
                fetchedAt: Date()
            )
            bpLog("WbiSigner prewarm: keys cached")
        } catch {
            // Non-fatal. First signed request will retry.
            bpLog("WbiSigner prewarm failed: \(error.localizedDescription)")
        }
    }

    /// Drop the cached WBI keys. Used when the upstream tells us our
    /// signature is no longer accepted (B站 rotates the img/sub keys on
    /// a cadence that outpaces our per-instance cache). The next signed
    /// request will re-fetch from `/x/web-interface/nav` and the
    /// caller's retry will succeed.  Clears both the per-instance and
    /// the boot-time static prewarm so a long-lived app can recover
    /// without a relaunch.
    func invalidate() {
        cachedKeys = nil
        Self.prewarmedKeys = nil
        bpLog("WbiSigner invalidated — keys will be re-fetched on next sign")
    }

    func sign(queryItems: [URLQueryItem], using session: URLSession) async throws -> [URLQueryItem] {
        let keys = try await loadKeys(using: session)
        let mixinKey = buildMixinKey(imgKey: keys.imgKey, subKey: keys.subKey)
        let timestamp = String(Int(Date().timeIntervalSince1970))

        var params: [String: String] = [:]
        for item in queryItems {
            guard let value = item.value else { continue }
            params[item.name] = value.replacingOccurrences(of: #"[!'()*]"#, with: "", options: .regularExpression)
        }
        params["wts"] = timestamp

        let sorted = params.keys.sorted().map { key in
            "\(key)=\(encodeURIComponent(params[key] ?? ""))"
        }.joined(separator: "&")
        params["w_rid"] = md5(sorted + mixinKey)

        return params.keys.sorted().map { key in
            URLQueryItem(name: key, value: params[key])
        }
    }

    private func loadKeys(using session: URLSession) async throws -> CachedKeys {
        if let cachedKeys, Date().timeIntervalSince(cachedKeys.fetchedAt) < keyTTL {
            return cachedKeys
        }
        // Lift the boot pre-warm into the per-instance cache
        // before going to the network.  Static cache is only
        // consulted when the instance cache is empty or
        // expired — TTL still applies.
        if let prewarmed = Self.prewarmedKeys,
           Date().timeIntervalSince(prewarmed.fetchedAt) < keyTTL {
            cachedKeys = prewarmed
            return prewarmed
        }

        var request = URLRequest(url: navURL)
        request.cachePolicy = .reloadIgnoringLocalCacheData
        request.setValue("https://www.bilibili.com", forHTTPHeaderField: "Referer")
        request.setValue(DeviceInfo.shared.userAgent, forHTTPHeaderField: "User-Agent")
        let (data, _) = try await session.data(for: request)
        let payload = try JSONDecoder().decode(WbiNavResponse.self, from: data)
        let imgURL = payload.data.wbiImg.imgURL
        let subURL = payload.data.wbiImg.subURL
        let keys = CachedKeys(
            imgKey: imgURL.deletingPathExtension().lastPathComponent,
            subKey: subURL.deletingPathExtension().lastPathComponent,
            fetchedAt: Date()
        )
        cachedKeys = keys
        return keys
    }

    private func buildMixinKey(imgKey: String, subKey: String) -> String {
        let source = Array(imgKey + subKey)
        let mixed = mixinKeyEncTab.compactMap { index in
            index < source.count ? source[index] : nil
        }
        return String(mixed.prefix(32))
    }

    private func encodeURIComponent(_ value: String) -> String {
        let allowed = CharacterSet.alphanumerics.union(CharacterSet(charactersIn: "-_.~"))
        return value.unicodeScalars.map { scalar in
            if allowed.contains(scalar) {
                return String(scalar)
            }
            let bytes = String(scalar).utf8.map { String(format: "%%%02X", $0) }
            return bytes.joined()
        }.joined()
    }

    private func md5(_ value: String) -> String {
        Insecure.MD5.hash(data: Data(value.utf8)).map { String(format: "%02x", $0) }.joined()
    }
}

enum BilibiliAPIError: Error, Sendable {
    case invalidURL
    case http
    case api(String)
    case missingData
    /// The endpoint we wanted to call requires an `aid` (or `bvid`) on the
    /// input and we have neither. Surfacing this as a typed error lets the
    /// caller show a clear "评论不可用" message instead of a generic
    /// "Could not load public comments." after a doomed network call.
    case missingIdentity
    /// The playurl endpoint returned a payload but every supported
    /// `qn` quality was gated (region lock, VIP paywall, 4K-only
    /// source). Distinct from `missingData` so the UI can say "暂无可
    /// 播放清晰度" rather than a generic "缺少数据".
    case noPlayableFormat
    /// The server returned HTTP 401 — the cookie session has
    /// expired or been invalidated (B站 rotates `SESSDATA` every
    /// ~30 days, and `bili_jct` after each login).  Distinct
    /// from `http` so the client can auto-open the login sheet
    /// and re-try the request once the user re-authenticates.
    case sessionExpired
    /// The user requested a quality / audio track that requires
    /// a 大会员 subscription but the active account does not
    /// have one. Carries the gated quality (when known) so the
    /// UI can render the matching toolbar label.
    ///
    /// Surfaced when the upstream playurl returns:
    ///   • `-62002` ("大会员已到期" — VIP lapsed)
    ///   • `-62004` ("4K 需要大会员" — 4K-only paywall)
    ///   • `-62012` ("1080P+ 需要大会员" — 1080P+ paywall)
    ///
    /// Distinct from `vipExpired` so the UI can split the
    /// "go upgrade" prompt (signed-in but not VIP) from the
    /// "your membership lapsed" prompt (signed-in, was VIP, now
    /// overdue). The two paths lead to different recovery
    /// actions — the former opens the upgrade page, the latter
    /// reopens the login sheet with the renewal hint.
    case vipRequired(gated: BiliVideoQuality?)
    /// The user had a 大会员 subscription but it has lapsed
    /// (`-40103` "大会员已到期" from the upstream playurl, or
    /// the nav `/x/web-interface/nav` `data.vip.status == 0`
    /// with a non-zero `due_date` in the past). Carries the
    /// gated quality (when known) so the UI can name the
    /// specific row that needs renewal.
    case vipExpired(gated: BiliVideoQuality?)

    /// B站 returns business code `-404` with the message
    /// `啥都木有` when a region/part feed (e.g. 音乐) has no
    /// items visible to the current viewer — either because
    /// the cookie is missing, the region is gated, or the
    /// upstream genuinely has nothing to show.  The wire
    /// response is the same shape as any other code, so
    /// callers normally get a thrown `api("啥都木有")`.  The
    /// UI, however, should treat this as the empty-feed
    /// state ("暂无音乐") rather than a network error.
    ///
    /// Use the `isEmptyFeed` helper below to check; do NOT
    /// pattern-match the raw message string at the call site.
    var isEmptyFeed: Bool {
        if case .api(let message) = self {
            return message == "啥都木有"
        }
        return false
    }

    /// True when the error is a 大会员-expired typed error
    /// (carries the `vipExpired(gated:)` case). Lets the
    /// `setPreferredQn` / `setPreferredAudioQuality` paths
    /// branch into the "续费" copy without pattern-matching
    /// the associated value at every call site.
    var isVipExpiredError: Bool {
        if case .vipExpired = self { return true }
        return false
    }
}

extension BilibiliAPIError: LocalizedError {
    var errorDescription: String? {
        switch self {
        case .invalidURL:
            return L10n.errors.parse
        case .http:
            return L10n.errors.network
        case .api(let message):
            // Forward the upstream message verbatim.  Anonymous
            // calls surface the well-known B站 business codes
            // here — e.g. `-404 啥都木有` ("nothing here") or
            // `-101 请先登录` ("please sign in").  Returning the
            // raw message lets callers show the upstream reason
            // instead of the unhelpful Swift default
            // "(Paladala.BilibiliAPIError error 0.)".
            return message
        case .missingData:
            return L10n.errors.parse
        case .missingIdentity:
            return L10n.errors.unauthorized
        case .noPlayableFormat:
            return L10n.errors.empty
        case .sessionExpired:
            return L10n.errors.unauthorized
        case .vipRequired:
            // "该画质/音质需要大会员" — the toolbar surfaces the
            // full "go upgrade" hint via the upgrade sheet; this
            // short message is what the inline `errorMessage`
            // banner shows until the user dismisses it.
            return L10n.vip.requiredHint
        case .vipExpired:
            return L10n.vip.expiredHint
        }
    }
}

struct EmptyPayload: Codable, Sendable {}

struct APIResponse<T: Decodable & Sendable>: Decodable, Sendable {
    let code: Int?
    let message: String?
    let data: T?
    let result: T?

    var value: T? {
        data ?? result
    }

    func requireOK() throws {
        guard let code, code != 0 else { return }
        // Surface the B站 大会员 business codes as typed errors so
        // the quality menu / audio menu can render an upgrade
        // hint instead of the raw upstream message. Anything else
        // stays a generic `.api(message)` so other endpoints keep
        // their existing fallback ("啥都木有", "请先登录", etc.).
        //
        // Code matrix (verified against `bilibili-API-collect` and
        // a live playurl call with a 大会员-cookie account vs.
        // anonymous):
        //   -40103 — "大会员已到期"            (was VIP, now lapsed)
        //   -62002 — "大会员未开通"            (signed-in but no VIP)
        //   -62004 — "4K 大会员限制"            (4K requires VIP)
        //   -62012 — "1080P+ 大会员限制"       (1080P+ requires VIP)
        //
        // `-62004` / `-62012` are returned as the *preferred qn*
        // request even when the qnChain would fall through; the
        // upstream still rejects the request shape. Treating them
        // as `vipRequired` lets the UI nudge the user without
        // burning the rest of the qnChain retries.
        switch code {
        case -40103:
            throw BilibiliAPIError.vipExpired(gated: nil)
        case -62002, -62004, -62012:
            throw BilibiliAPIError.vipRequired(gated: nil)
        default:
            throw BilibiliAPIError.api(message ?? "Bilibili API returned code \(code)")
        }
    }
}

